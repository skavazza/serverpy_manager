class InterfaceLanguage:
    def __init__(self, code="en"):
        self.code = code if code in ("en", "pt") else "en"

    def text(self, source, **values):
        translated = PORTUGUESE.get(source, source) if self.code == "pt" else source
        return translated.format(**values) if values else translated

    def capture(self, root):
        """Remember source labels once; never translate editable values."""
        properties = []
        for widget in [root] + root.findChildren(QObject):
            names = ("placeholderText",) if isinstance(widget, QLineEdit) else ("text", "title", "windowTitle", "toolTip")
            if isinstance(widget, QComboBox):
                continue
            for name in names:
                value = widget.property(name)
                if isinstance(value, str) and value:
                    properties.append((widget, name, value))
        return properties

    def apply(self, properties):
        for widget, name, source in properties:
            widget.setProperty(name, self.text(source))
